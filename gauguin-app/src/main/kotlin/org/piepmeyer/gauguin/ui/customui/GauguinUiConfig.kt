/**
 * The groups the non-colour knobs (sliders, switches, fonts) are declared in. Each is shown in its
 * [section] of the UI page, under that section's colours.
 */
enum class UiCategory(
    val id: String,
    val section: SkSection,
) {
    GLOBAL("ui.global", SkSection.FOUNDATION),
    GRID("ui.grid", SkSection.GRID),
    KEYPAD("ui.keypad", SkSection.KEYPAD),
    TOP_PANEL("ui.toppanel", SkSection.TOP),
    DRAWER("ui.drawer", SkSection.DRAWER),
    DIALOG("ui.dialog", SkSection.DIALOGS),
    LISTS("ui.lists", SkSection.LISTS),
}
